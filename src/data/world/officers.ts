const seen = new Set<string>();
export const historicalOfficers: HistoricalOfficer[] = groups.flatMap(
  ([group, text]) =>
    text
      .split(/\s+/)
      .filter(Boolean)
      .flatMap((word) => {
        const [name, birth, death, role] = word.split(":");
        if (seen.has(name) || fictional.has(name)) return [];
        seen.add(name);
        const born = Number(birth) || undefined;
        return [
          {
            id: `h-${[...name].map((c) => c.codePointAt(0)!.toString(16)).join("-")}`,
            name,
            born,
            died: confirmedDeaths.has(name)
              ? Number(death) || undefined
              : undefined,
            until: Number(death) || 300,
            from: Math.max(from[name] ?? 194, born ? born + 16 : 0),
            group,
            role,
          },
        ];
      }),
);
const hash = (s: string) =>
  [...s].reduce((n, c) => (n * 31 + c.charCodeAt(0)) >>> 0, 7);
export function historicalRating(
  h: HistoricalOfficer,
): Pick<
  Officer,
  "leadership" | "strength" | "intelligence" | "politics" | "charm"
> {
  const n = hash(h.name),
    r = h.role;
  return {
    leadership:
      r === "l" ? 82 + (n % 15) : r === "m" ? 66 + (n % 29) : 45 + (n % 35),
    strength: r === "m" ? 76 + ((n >>> 3) % 23) : 30 + ((n >>> 3) % 40),
    intelligence:
      r === "s"
        ? 80 + ((n >>> 5) % 19)
        : r === "c"
          ? 65 + ((n >>> 5) % 27)
          : 40 + ((n >>> 5) % 41),
    politics:
      r === "c" || r === "s" ? 75 + ((n >>> 7) % 23) : 35 + ((n >>> 7) % 40),
    charm: r === "l" ? 80 + ((n >>> 9) % 18) : 50 + ((n >>> 9) % 43),
  };
}
